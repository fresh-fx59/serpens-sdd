/**
 * YAML single-quote a scalar (`'` doubled inside). Every generated `run:` value goes through
 * this: the shim invocation begins with a double-quoted `"$(git rev-parse --show-toplevel)"`
 * followed by more text, which YAML rejects as a plain or double-quoted scalar — real lefthook
 * 2.1.4 refused the whole file (`yaml: line 8: did not find expected key`, step-6 repro,
 * 2026-09-23). Single quotes keep every character literal for the shell lefthook hands it to.
 * @param {string} value
 * @returns {string}
 */
export function yamlSingleQuote(value) {
  return `'${String(value).replaceAll("'", "''")}'`;
}

/**
 * Render the lefthook config, reproducing kits/<lang>/config/lefthook.yml.example verbatim
 * (including its comments), with each `<serpens-sdd> <subcommand>` placeholder replaced by the
 * resolved invocation. The YAML structure and every `run:` line are identical across
 * languages; only the inline comments differ, taken verbatim from each kit's own example.
 * @param {string} invocation
 * @param {'en'|'ru'} [lang]
 * @returns {string}
 */
export function renderLefthook(invocation, lang = 'en') {
  const c = LEFTHOOK_COMMENTS[lang] ?? LEFTHOOK_COMMENTS.en;
  const q = (sub) => yamlSingleQuote(`${invocation} ${sub}`);
  return `${LEFTHOOK_MARKER}
pre-commit:
  parallel: true
  commands:
    serpens-docs:
${c.serpensDocsScope}
      run: ${q('verify-docs --staged-scope')}
${c.branchConvention}
    serpens-branch:
      run: ${q('git-naming --branch')}

commit-msg:
  commands:
    serpens-commit-msg:
${c.commitMsgArg}
      run: ${q('git-naming --commit-msg {1}')}

pre-push:
  commands:
    serpens-branch:
${c.prePushBackstop}
      run: ${q('git-naming --branch')}

${LEFTHOOK_EXTENDS_NOTE[lang] ?? LEFTHOOK_EXTENDS_NOTE.en}
`;
}
